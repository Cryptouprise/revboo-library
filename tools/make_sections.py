#!/usr/bin/env python3
"""Build catalog/sections.json: the library split into FINALS (approved to run) and DRAFTS & MOCKUPS (everything else).

  python3 tools/make_sections.py          # also run automatically at the end of build.py

Inputs (read-only): manifest.json (media, dates), catalog/registry.json (approved_ranking, concepts, revision
records), finals.json (FINALS.md list incl. rejected), catalog/sections_config.json (curation).
Status per item: final = in approved_ranking / FINALS approved list / an Approved|Live revision record;
rejected = manifest status rejected, FINALS rejected list, a Rejected revision record or a config override;
draft = everything else (legacy "final" labels are historical, not approval: docs/AGENT_WORKFLOW.md).
Dates are copied from manifest.json (stored metadata). Nothing is ever dropped: every manifest id appears once.
"""
import json,os,re
L=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))+'/'
def load(p,d=None):
    try: return json.load(open(L+p))
    except Exception: return d
def main():
    m=load('manifest.json'); reg=load('catalog/registry.json',{}); fj=load('finals.json',{}); cfg=load('catalog/sections_config.json',{})
    ranks=sorted(reg.get('approved_ranking',[]),key=lambda x:x['rank'])
    rank_of={a:x for x in ranks for a in x.get('asset_ids',[])}
    recs=reg.get('revision_records',{})
    approved=set(rank_of)|{v.get('id') for v in fj.get('approved_videos',[])}|{k for k,v in recs.items() if v.get('status') in('Approved','Live')}
    rejected={v.get('id') for v in fj.get('rejected',[])}|{k for k,v in recs.items() if v.get('status')=='Rejected'}
    concept_of={a:c for c in reg.get('concepts',[]) for a in c.get('assets',[])}
    so=cfg.get('status_overrides',{}); fo=cfg.get('folder_overrides',{}); cl=cfg.get('concept_labels',{})
    def client(e,kind):
        t=' '.join(str(e.get(k,'')) for k in('id','category','group','title','name','source')).lower()
        for r in cfg.get('client_rules',[]):
            if r.get('kind') and r['kind']!=kind: continue
            if r.get('brand') and r['brand']!=e.get('brand'): continue
            if r.get('match') and not re.search(r['match'],t): continue
            return r['client']
        return e.get('brand') or 'Generic/Other'
    items=[]
    for kind,key in (('ad','finals'),('clip','clips')):
        for e in m.get(key,[]):
            i=e['id']; c=concept_of.get(i,{})
            st=so.get(i) or ('final' if i in approved else 'rejected' if (e.get('status')=='rejected' or i in rejected) else 'draft')
            group=e.get('group') or e.get('name') or e.get('title')
            if kind=='ad':
                folder=fo.get(e.get('category',''),e.get('category') or 'Ads'); concept=cl.get(group,group)
            else:
                folder='Source clips (B-roll)'; concept=(e.get('categories') or ['Other'])[0]
            t=' '.join([group or '',e.get('title',''),e.get('name','')])
            for r in cfg.get('concept_folder_rules',[]):
                if re.search(r['match'],t,re.I): folder,concept=r['folder'],r['concept']
            it=dict(id=i,kind=kind,client=client(e,kind),section='finals' if st=='final' else 'mockups',status=st,
                    folder=folder,concept=concept,concept_id=c.get('concept_id'),title=e.get('title') or e.get('name'),
                    version=e.get('version',''),date=e.get('date'),datetime=e.get('datetime'),duration=e.get('duration'),
                    width=e.get('width'),height=e.get('height'),video=e.get('video'),poster=e.get('poster'),note=e.get('note',''),
                    legacy_status=e.get('status'))
            if kind=='clip': it.update(categories=e.get('categories',[]),used_in=e.get('used_in',[]))
            if i in rank_of:
                x=rank_of[i]; it.update(rank=x['rank'],concept=x['title'],approved_by=x.get('approved_by'),approved_at=x.get('approved_at'),folder='★ Approved to run')
            items.append(it)
    for p in cfg.get('placeholders',[]):
        if not any(x['concept']==p['concept'] and x['kind']!='placeholder' for x in items):
            items.append(dict(p,kind='placeholder',section='mockups'))
    ids=[x['id'] for x in items]; assert len(ids)==len(set(ids)),'duplicate ids'
    assert {x['id'] for x in items if x['kind']!='placeholder'}=={e['id'] for k in('finals','clips') for e in m.get(k,[])}
    # a concept is "rejected" in the archive when every version in it is rejected
    fam={}
    for x in items: fam.setdefault((x['client'],x['folder'],x['concept']),[]).append(x['status'])
    for x in items: x['concept_rejected']=all(s=='rejected' for s in fam[(x['client'],x['folder'],x['concept'])])
    out=dict(_doc='Generated by tools/make_sections.py; do not hand-edit (edit catalog/sections_config.json or the source records).',
             client_order=cfg.get('client_order',[]),client_notes=cfg.get('client_notes',{}),
             finals_rank=[dict(rank=x['rank'],title=x['title'],concept_id=x.get('concept_id'),asset_ids=x.get('asset_ids',[]),approved_at=x.get('approved_at')) for x in ranks],
             counts=dict(finals=sum(x['section']=='finals' for x in items),mockups=sum(x['section']=='mockups' for x in items),
                         final=sum(x['status']=='final' for x in items),draft=sum(x['status']=='draft' for x in items),rejected=sum(x['status']=='rejected' for x in items)),
             items=items)
    json.dump(out,open(L+'catalog/sections.json','w'),indent=1,ensure_ascii=False)
    print('sections:',out['counts'])
if __name__=='__main__': main()
